package store

import "context"

// TxHandle 是事务句柄，即约定 7 所说「store 定义事务句柄类型，L5 内跨包同事务
// 调用以**首参**传递，不塞进 context，L2 与 L3 以下不感知」的那个类型。
//
// # 为什么是不透明接口（sealed interface）
//
// 常见做法是把 *sql.Tx 直接暴露出来，或定义一个带 Exec/Query 方法的接口。两者都
// 会让「唯一知道 SQL 的地方是 store/sqlite」当场失效（分层 §六 L4 明写这条）：
// L5 拿到句柄后可以直接执行任意语句，绕过全部仓储签名——连不变式 3 的归属参数
// 都一起绕过了，因为手写的 SQL 里没有人强制 WHERE owner_user_id = ?。
//
// 故本接口只有一个**未导出**方法：
//
//   - L4 之外的包无法实现它（未导出方法名不可跨包实现），因此句柄的来源唯一，
//     只能是 TxExecutor 交给回调的那个；
//   - L5 拿到它也无法从中取出任何数据库对象，只能原样往下传（这正是约定 7
//     要的：intake/file → audit 的透传）。
//
// # 为什么不用 context 传递
//
// 约定 7 明写「不塞进 context」。理由是塞进 context 之后，「这个方法是否在事务里」
// 就从签名上消失了：一个漏传句柄的调用在编译期与运行期都毫无征兆，只是悄悄地
// 在事务外执行了——D-7 的「一条审计 + N 条明细同事务」会退化成「审计已提交、
// 明细失败」，而不变式 4 是「一次提交 = 一条审计 = 一个批次」。做成首参之后，
// 事务边界在每个签名上都是可见的。
//
// # 零值与 nil
//
// nil TxHandle 表示「不在事务中」。各仓储方法**同时**接受两种形态：
// 带句柄的方法（Tx 后缀）与不带句柄的方法。理由见 TxExecutor 的注释。
type TxHandle interface {
	// isTxHandle 是标记方法，无实际行为。
	//
	// 命名以小写开头即包私有，这是「只有 L4 能实现本接口」的语言级保证。
	// 不用空接口 any：那样任何值都是合法句柄，包括一个手写的 struct{}，
	// 装配错误就不会在编译期暴露。
	isTxHandle()
}

// TxExecutor 是事务执行器（承载 ⑦），跨仓储同事务的唯一入口。
//
// 分层 §六 L3 store ⑦：「事务执行器 + 事务句柄类型（跨仓储同事务，**D-7 与 I-7
// 的事务边界由它提供**；句柄在 L5 内以显式入参透传，见约定 7）」。
//
// # 两个用例的事务粒度完全不同
//
//	D-7 提交入库    一条「数据入库」审计 + N 条明细，**一个大事务**（不变式 4）
//	I-7 逐笔重算    单笔的三字段更新，**每笔一个小事务**（不变式 2）
//
// 后者「允许部分失败、可中断可续跑」（终版 I-7），所以绝不能把整轮重算包进一个
// 事务——那样一笔失败就整轮回滚，「可续跑」失去意义。这不是本包能强制的事情
// （调用方自己决定 WithinTx 的调用粒度），但 store/sqlite 的口径「写连接单例 +
// WAL + busy_timeout」会让「I-7 的逐笔小事务与 D-7 的大事务天然串行」
// （分层 §六 L4），因此两者不会互相阻塞成死锁。
//
// # 另一条同样要紧的用例：G-4 的引用检查与物理删除
//
// §九 前提 8 行：「ExpenseCategory 物理删除须先过引用检查（**与删除同事务**）」。
// 分层 §六 L5 service/category 行给出了理由：「检查与删除同事务，否则 TOCTOU」
// ——检查完、删除前的这段时间里，另一个请求正好插入一条引用该类型的明细，
// 删除就会留下一条指向不存在类型的明细。
type TxExecutor interface {
	// WithinTx 在一个事务内执行 fn，并把事务句柄交给它。
	//
	// # 提交与回滚的判据只有一条：fn 的返回值
	//
	//	fn 返回 nil     → 提交；若提交本身失败，返回提交错误
	//	fn 返回非 nil   → 回滚，并**原样返回 fn 的错误**
	//
	// 原样返回是硬要求：fn 里产生的错误往往已经是带档位与文案键的
	// base/errs（例如 G-1 撞了唯一索引 → 409），若在此包一层「事务失败」，
	// 档位与文案键就丢了，middleware 只能按 500 渲染，用户看到「系统错误」
	// 而不是「同名类型已存在」。
	//
	// 若回滚动作自身也失败，实现应把回滚错误记入日志但**仍返回 fn 的错误**
	// ——调用方需要知道的是业务上为什么没成，回滚失败是运维问题。
	//
	// # panic 必须回滚后重新抛出
	//
	// fn 是上层传进来的闭包，可能 panic。实现必须 defer 一个回滚，否则事务
	// 悬挂、连接不归还，而 store/sqlite 是**写连接单例**——一次悬挂就让全库
	// 的写入永久阻塞。捕获后应重新 panic：把 panic 转成 error 会掩盖一个真正
	// 的程序缺陷。
	//
	// # 不支持嵌套
	//
	// 实现**不得**在已有事务内再开一个事务（也不必支持保存点）。本系统里没有
	// 嵌套事务的用例：D-7 与 I-7 的事务边界都在 service 层的一个方法内开合，
	// 而约定 7 要求句柄显式透传——一个已经拿到句柄的方法应当调用带 Tx 后缀的
	// 仓储方法，而不是再开一层。若实现检测到嵌套调用，应返回错误而非静默地
	// 把内层当成外层的一部分（后者会让内层的「回滚」什么也不做）。
	//
	// ctx 用于取消与向 base/log 透传请求标识（约定 4）。ctx 取消时实现应回滚。
	WithinTx(ctx context.Context, fn func(tx TxHandle) error) error
}
