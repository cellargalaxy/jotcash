// Package store 是 jotcash 的持久化**端口层**（L3）：只定义仓储接口、查询条件
// 类型、数值列口径、唯一约束语义与事务句柄，**不含任何 SQL、不含任何具体存储
// 引擎的痕迹**。
//
// # 承载
//
// 依据 doc/decisions/仓库代码包的层级设计与划分.md（下称「分层」）§六 L3 表
// store 行，本包承载七项：
//
//	① 归属型仓储 4 个（Expense/File/AuditLog/ExpenseCategory）——每个按 ID
//	   访问的方法签名强制带归属用户ID，不变式 3 的编译期兜底，该参数对任何角色
//	   一律生效、无管理员旁路（前提 3）
//	② User 仓储——不带归属参数，无删除方法
//	③ 删除能力按前提 8 裁剪；Expense 只有「写删除时间」，形态有二（按 ID 与
//	   按筛选条件批量），一律已删除行跳过、不覆盖其删除时间（幂等）、返回实际
//	   受影响笔数
//	④ 查询条件类型：十条查询口径
//	⑤ 唯一性约束口径：两项唯一索引，冲突返回 base/errs 的「唯一冲突」档
//	⑥ 数值列口径：金额与汇率一律非浮点
//	⑦ 事务执行器 + 事务句柄类型
//
// 另有两处性能口径：File 元信息与二进制内容**分接口**、Expense 提供**游标
// 迭代**（I-7 与 K-3 不全量装载）。
//
// 七项与两处性能口径的落点见各文件的包内注释；十条查询口径逐条落在 query.go。
//
// # 端口在下、实现在上
//
// 分层 §六 L3 表头把 store / fxrate / parser 归为**端口包**：「只有接口、类型
// 与注册表，实现在 L4」；准则 4 写明「端口在下、实现在上……实现子包按选型命名
// （store/sqlite），换选型 = 加平级子包 + 改 app 一行」；§十一 阶段 4 对本包的
// 完成标志是「方法集合须通过『前提 8 + 不变式 3 + 前提 3 无角色旁路 + 十条查询
// 口径 + 两种软删除形态 + 两项唯一约束 + 数值列口径 + 事务句柄』走查」。
//
// 因此本包：
//
//   - **不 import database/sql、不 import 任何数据库驱动**。哪怕只是为了拿一个
//     sql.Tx 类型——那会把「关系型数据库」这一选型固化进端口层，且让 L5 有机会
//     直接写 SQL。TestDependencyBoundary 用 AST 扫描锁死这条。
//   - **不 import 任何 ORM 或查询构建器**（GORM/ent/sqlc/squirrel 等）。它们的
//     仓储接口以自己的模型与 DSL 表达，出现在 L3 会让 L5 的 11 个 service 全部
//     编译期依赖某个具体 ORM，而分层 §十二 明写「换/加存储引擎」的代价应为
//     「新增 store/pg 等平级子包 + app 改一行装配，store 端口与 L5 不动」。
//     注：go.mod 里的 gorm.io/gorm 是 go_common 带进来的 indirect 依赖，
//     本仓库 internal/ 下无一处 import 它。
//   - **不含建表与迁移脚本**。那是 store/sqlite 的承载（分层 §六 L4）。
//   - **不做业务编排**。「先落审计取 ID → 业务数据挂载该 ID → 同事务提交」是
//     service/audit 的语义（不变式 4），本包只提供事务句柄让它成立。
//
// # 五条结构性红线
//
// 这五条不是风格取向，每一条都有「漏一处即全量泄漏或静默丢数」的后果，且都在
// 本包做成了**编译期或测试期**的约束，而非注释里的君子协定。
//
// ## 红线 1：归属参数不可省、不可传反、不可被角色旁路
//
// 不变式 3 是「归属校验无死角」，§九 给它的唯一实现处就是本包的 4 个归属型
// 仓储签名。前提 3 进一步写明「4 个归属型仓储不存在管理员旁路，service/* 不得
// 按角色放宽归属过滤。这是不变式 3 最易被『顺手加个 if』破坏的一处」。
//
// 落地形态是三条：
//
//  1. 归属用户ID 用具名类型 OwnerUserID，**不用裸 int64**。理由是传反不会报错
//     ——用明细ID 当归属用户去查，恒查不到，表现为「数据莫名消失」，而不是一条
//     错误。具名类型让传反成为编译错误。
//  2. 该参数固定在 ctx（与 TxHandle，若有）之后的**首位**，全包无例外。
//  3. 本包**不存在任何以角色为入参的方法**。角色（enum.Role）根本不出现在本包
//     的任何签名里，于是「管理员就放宽过滤」在本层无法表达。
//     TestNoRoleInSignatures 扫描 AST 钉住这条。
//
// ## 红线 2：「不存在」与「归属不符」返回同一个错误
//
// 若把两者分成两个错误，错误本身就成了存在性预言：拿别人的明细ID 来查，得到
// 「这条存在但不属于你」，等于确认了该 ID 有效——这正是不变式 3 要防的泄漏，
// 只是泄漏的是存在性而非内容。故一律 KeyNotFound（见 errors.go）。
//
// ## 红线 3：前提 8「存在性单向不可逆」由方法集合本身保证
//
// §九 前提 8 行：「User/File/AuditLog 仓储无删除方法；Expense 仅『写删除时间』；
// ExpenseCategory 物理删除须先过引用检查（与删除同事务）。**上层想违反也没有
// 可调的方法**」。因此本包的三个接口连一个带 Delete 字样的方法都不能有，
// TestNoDeleteMethods 按接口逐个断言方法集合。
//
// ## 红线 4：密码哈希与盐不进任何裁剪型返回
//
// §九 密码红线：「密码哈希与盐连三类出口都不得出现——dto 不定义、A-7 列表裁剪、
// K-3 导出裁剪」。裁剪发生在 service/account 与 service/export，但本包的 User
// 列表口径必须让裁剪成为可能：故列表返回完整 entity.User 而**不**返回自定义的
// 「安全视图」结构——后者会诱使 store 承担裁剪职责，而裁剪点一旦有两处
// （store 一处、service 一处）就必然漂移。本包只做一件事：在 UserRepo 的注释里
// 把「返回值含密码哈希与盐，调用方必须裁剪」写成硬约定。
//
// ## 红线 5：金额与汇率一律非浮点，且列位数有三套口径
//
// 见 column.go。承载 ⑥ 的措辞是「金额 2 位定点、汇率 8 位定点」，但**支出金额
// 一列不能是恒 2 位**——KWD 是 3 位小数币种，按 2 位落库会直接丢掉第 3 位。
// 三套口径的划分与实测依据见 column.go 的包内注释。
//
// # 事务句柄不透明
//
// 约定 7：「store 定义事务句柄类型，L5 内跨包同事务调用（intake/file → audit）
// 以**首参**传递，不塞进 context，L2 与 L3 以下不感知」。
//
// 本包把 TxHandle 做成只含未导出方法的接口（sealed interface）：L4 之外无人能
// 实现它，L5 拿到它也只能原样往下传、无法从中取出任何数据库对象。若像常见做法
// 那样暴露 *sql.Tx，L5 立刻就能自己写 SQL，「唯一知道 SQL 的地方是 store/sqlite」
// 当场失效。
//
// # 并发
//
// 各仓储接口的实现由 L4 负责并发安全（store/sqlite 的口径是「写连接单例 + WAL
// + busy_timeout」，见分层 §六 L4）。本包定义的全部类型都是**值语义的纯数据**，
// 无包级可变状态，天然可并发使用。
//
// # 错误
//
// 一律返回 base/errs 的分档错误并带文案键，供 middleware 映射 HTTP 状态与经
// i18n 取词（K-4）。本包声明的文案键见 errors.go，**语言文件必须包含它们全部**
// （与 parser、rule/passwd 同例）。
package store

import (
	"github.com/cellargalaxy/jotcash/internal/base/idgen"
)

// OwnerUserID 是归属用户ID，即不变式 3 的编译期兜底所依赖的那个具名类型。
//
// # 为什么不是裸 int64
//
// 本包几乎每个按 ID 的方法都同时接收「对象ID」与「归属用户ID」两个整数。若二者
// 都是裸 int64，把它们传反在语法上毫无阻力，而后果**不是报错**：以明细ID 作为
// 归属用户去查，条件恒不成立，返回「未找到」。排错时看到的现象是「数据莫名消失」
// ，离根因（调用处两个实参写反了）极远。
//
// 具名类型把这类错误挪到编译期。代价是调用方要写一次显式转换
// （store.OwnerUserID(userID)），这正是想要的效果：那次转换是一个可被评审看见的
// 「我确认这是归属用户」的断言。
//
// # 与前提 3 的关系
//
// 本类型对任何角色一律生效。§九 前提 3 明写「4 个归属型仓储不存在管理员旁路」，
// 因此本包不提供任何「跳过归属过滤」的取值——**零值不是通配符**，见 IsValid。
//
// # 唯一的例外是 User 仓储
//
// §九 不变式 3 行：「User 仓储是唯一签名不带归属的仓储」，理由是 A-1 初始化、
// A-4 按用户名登录、A-7 管理员按目标用户ID 三类操作根本没有「当前归属用户」这个
// 概念。越权由服务层按 §九 白名单显式校验。故 UserRepo 的方法接收裸 int64
// 形态的用户ID（见 user.go 的 UserID 说明），刻意与本类型区分开——**签名形状
// 上的差异本身就是那条白名单的提示**。
type OwnerUserID int64

// IsValid 报告该归属用户ID 是否可用于查询。
//
// 判据直接复用 base/idgen.IsValid（约定 9：实体标识一律由 base/idgen 生成），
// 因此零值、负值与非本系统生成的 ID 一律为 false。
//
// **零值不是「查全部用户」的通配符**：前提 3 不允许任何跨归属的读取形态存在。
// L4 各实现应在方法入口用它做一次判定，把「调用方忘了填归属」这类接线错误在
// 端口边界拦下，而不是让它退化成一次全表扫描或一次空结果。
func (o OwnerUserID) IsValid() bool {
	return idgen.IsValid(int64(o))
}

// Int64 返回底层整数值，供 L4 实现拼查询参数。
//
// 提供显式方法而不让调用方写 int64(o)：后者在 L4 的 SQL 拼装处会与「明细ID」
// 等其他 int64 混在一行里，具名类型带来的可读性当场消失。
func (o OwnerUserID) Int64() int64 {
	return int64(o)
}

// Store 是全部仓储与事务执行器的聚合入口，即 app 构造 store/sqlite 后**以接口
// 类型注入 L5** 的那个类型（分层 §六 L7 app 行）。
//
// # 为什么要有聚合接口
//
// L5 的 11 个 service 各自只用到其中一两个仓储，按最小接口原则本该各自声明自己
// 需要的窄接口。本包仍提供这个聚合接口，理由是分层 §六 L5 表把 store 列为 11 个
// service 中 10 个的依赖项，而 app 是「唯一 import 具体实现的地方」——聚合接口
// 让装配处只需一次类型断言，而不是为每个 service 各拼一个适配器。
//
// 各 service 若愿意声明自己的窄接口（例如只要 ExpenseRepo 的三个方法），本包
// 不阻止也不需要改动：Go 的接口是隐式满足的。
//
// # 不含 Close
//
// 生命周期由 app 管理（分层 §六 L7「执行迁移、优雅退出」）。把 Close 放进这个
// 接口，等于让每个拿到 Store 的 service 都有权关掉整个数据库连接池。
// L4 的具体类型自然可以有 Close，由 app 直接调用其具体类型上的方法。
type Store interface {
	// TxExecutor 是事务执行器，跨仓储同事务的唯一入口（承载 ⑦）。
	TxExecutor

	// Users 返回 User 仓储（承载 ②）。
	Users() UserRepo

	// Expenses 返回 Expense 仓储（承载 ①）。
	Expenses() ExpenseRepo

	// Files 返回 File 仓储（承载 ①）。
	Files() FileRepo

	// AuditLogs 返回 AuditLog 仓储（承载 ①）。
	AuditLogs() AuditLogRepo

	// Categories 返回 ExpenseCategory 仓储（承载 ①）。
	Categories() CategoryRepo
}
