package entity

import (
	"time"

	"github.com/cellargalaxy/jotcash/internal/enum"
)

// File 是文件，承载终版 §四 4 的 11 项属性，**仅文件密码非必填**。
//
// # 只留存不物理删除，因此没有删除标记
//
// 终版前提 8 把 File 列为「一律不可删除」的三个实体之一，§四 4 表下注亦明写
// 「文件只留存不物理删除，因此没有删除标记；允许重复上传、重复保存」。
// C-4 同样明写「不做文件级查重」——去重只发生在明细层面（E-1 的四要素），
// 与文件无关。
//
// # 格式与解析器类型是正交两列
//
// 这是本实体最容易被误解的一点，终版 §四 4 对二者的定性截然不同：
//
//	Format      文件类型标识，用于展示、预览与下载；**不决定解析器**
//	ParserType  **决定走哪个解析器**，由用户在上传页显式选择
//
// D-1 给了理由：「格式不足以判定——同为 PDF，各银行版式不同」。因此不能用 Format
// 反推 ParserType，也不能省掉其中任何一列。二者的关系是「解析器声明自己吃哪种
// 格式」（enum.ParserMeta.Format），service/file 据此实现 D-3 第五类错误
// 「所选解析器类型与文件不匹配」——在解析前就能拦下。
type File struct {
	// ID 文件ID，唯一标识（终版 §四 4）。
	//
	// 由 base/idgen.GenFileID() 生成，唯一调用方 service/file（C-1 上传入库）。
	ID int64

	// OwnerUserID 归属用户ID。下载时的越权校验依据（终版 §四 4 / B-3）。
	OwnerUserID int64

	// SourceAuditID 来源审计ID。在哪次「文件上传」操作中上传——文件与审计
	// **双向可查**（终版 §四 4 / C-3）。
	//
	// 挂的是「文件上传」那条审计（8.4 第 5 类），与 Expense.SourceAuditID 挂
	// 「数据入库」那条是两条不同的审计（终版 8.4）。双向查询的两侧分别是
	// store 的「按来源审计ID 查 File」（C-3 反向）与本字段本身（正向）。
	SourceAuditID int64

	// Name 原始文件名，用户上传时的文件名（终版 §四 4）。
	Name string

	// Format 格式，**文件类型标识**，用于展示、预览与下载（CSV / Excel / PDF）；
	// **不决定解析器**（终版 §四 4）。
	//
	// 用 enum.FileFormat 而非裸 string（分层 §六 L1.1），恰 3 项（终版 C-2）。
	Format enum.FileFormat

	// ParserType 解析器类型，**决定走哪个解析器**；取值为代码内置解析器类型枚举
	// 的键，**由用户在上传页显式选择**（终版 §四 4 / D-1 / D-2）。
	//
	// 库中只存键（终版 §五 2），实现体不在枚举里——注册表在 parser（L3）、
	// 实现体在 parser/csv（L4），准则 3。历史行可能存着已停用的键，因此
	// enum.ParserType 的 Scan 建立在「已知」而非「已启用」上（§五 2：
	// 枚举项只能停用不能删除）。
	ParserType enum.ParserType

	// Size 文件大小，用于展示（终版 §四 4）。
	//
	// 用 int64 而非 int：32 位平台上 int 为 4 字节，虽然个人账单不会超过 2GB，
	// 但文件大小按惯例用 int64，且与标准库 os.FileInfo.Size() 的类型一致，
	// 赋值处不必转换。
	Size int64

	// Content 文件内容，**原始二进制随记录存储**，无外部存储位置（终版 §四 4 / C-2）。
	//
	// 存 BLOB 于业务表同库（分层 §六 L4 store/sqlite 行），已登记的代价是
	// 库文件膨胀、备份即整库拷贝。K-3 整库导出**含本字段**（终版 K-3），
	// 与前提 1 的明文口径一致。
	//
	// # nil 与空切片在此有区别，是唯一需要区分二者的字段
	//
	// 分层 §六 L3 store 行定死「File 元信息与二进制内容**分接口**」，目的是让
	// C-1 管理页与 F-4「来源文件」下拉「**只取元信息**」而不搬运二进制。于是
	// 一个 File 值可能处于两种状态：
	//
	//	Content == nil        只查了元信息，内容**未加载**（不代表文件是空的）
	//	len(Content) == 0 且非 nil  内容已加载且确实是零字节
	//
	// 调用方据此区分「没读」与「读了是空的」。**这不同于其余 8 个可空字段**
	// ——它们一律以零值表达「无」，不区分未加载。
	Content []byte

	// Checksum 内容校验值，**仅作特征值留存**；系统无校验功能，也不用于查重
	// （终版 §四 4 / C-2 / C-4）。
	//
	// 这条定性是显式接受的（终版 §十二 校验方式④ 把它列为「反向校验的四个薄弱项」
	// 之一，落点为「显式接受为纯留存」）：既不校验也不查重，只是留个特征值。
	// C-4 明写「允许重复上传、重复保存，不做文件级查重」。
	Checksum string

	// Password 文件密码，加密文档的解密口令，**明文保存**；非加密文档为空
	// （**唯一非必填项**，终版 §四 4）。
	//
	// 明文保存是前提 1 的直接后果（「数据一律明文存储（含上传文件与文件密码），
	// 密码是唯一例外」——那个例外指的是 User 的登录密码，不含本字段）。
	// 保存的目的是「供重新打开」（C-2）。
	//
	// **不加 json:"-"**，与 User.PasswordHash 刻意不同：分层 §九 红线行的密码
	// 红线管的是「用户登录密码」，本字段是文件解密口令，且 K-3 导出明写「File
	// 的 文件内容 与 文件密码 **照导**」。给它加 json:"-" 会让 K-3 的导出口径
	// 与终版直接冲突。
	Password string

	// UploadTime 上传时间（终版 §四 4）。
	//
	// 本实体**只有上传时间，没有创建/更新时间**——终版 §四 4 的 11 项里就是
	// 这一个时间戳。文件只留存不修改，一个时刻足够表达其生命周期。
	UploadTime time.Time
}
