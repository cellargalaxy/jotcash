// Package entity 是 jotcash 的领域定义层（L1.1），承载 5 实体 62 属性的结构体定义。
//
// # 承载与边界
//
// 依据 doc/decisions/仓库代码包的层级设计与划分.md（下称「分层」）§六 L1.1 表
// entity 行，本包承载「5 实体 62 属性的结构体定义（User 15 / ExpenseCategory 5 /
// Expense 22 / File 11 / AuditLog 9），**零方法**；币种、角色、状态、操作类型等
// 字段直接用 L1.0 的枚举类型，金额与汇率用 base/decimal、日期与年月用
// base/calendar，不用裸 string」，恰是这些，一项不多一项不少。
//
// 属性点算与 doc/decisions/记账系统功能与模型.md（下称「终版」）§十二 校验方式②
// 三向对齐：15 + 5 + 22 + 11 + 9 = 62；Expense 另按「可编辑 8 + 只读派生 4 +
// 系统只读 10 = 22」与「F-1(8) + F-2(14) = 22」两条独立路径复核。三向都由
// field_golden_test.go 的可执行断言锁死，改字段必然在此失败。
//
// # 零方法：本包只声明「有哪些属性」，不声明「它们怎么变」
//
// 全部 5 个结构体既无值方法也无指针方法，这不是省事，而是分层设计把「属性」与
// 「规则」彻底分开的落点：
//
//	折算恒等式与三字段联动（不变式 1a）  唯一实现处 rule/convert
//	摊分起止月与份额均分（不变式 1b）    唯一实现处 rule/amortize
//	四要素判重（8.3）                    唯一实现处 rule/dedup
//	密码策略（A-8）                      唯一实现处 rule/passwd
//	归属校验（不变式 3）                 唯一实现处 store 的归属型仓储签名
//	审计写入（不变式 4）                 唯一实现处 service/audit
//
// 一旦本包出现 `func (e *Expense) Recalc()` 这类方法，上述任一不变式就多出第二处
// 实现，而准则 1 明写「一条不变式只有一处实现，其余包只能调用」。零方法是这条准则
// 在 L1.1 的结构表达，由 TestEntitiesHaveNoMethod 用反射对 5 个类型的值形态与指针
// 形态双向断言。
//
// 「零方法」也意味着本包**不含构造函数与校验函数**。合法性由字段类型自身保证：
// currency.Code、calendar.Date、calendar.Month 三者字段私有，只能经各自的
// Parse / New 构造，于是「一个值要么 IsZero，要么合法」这条性质自动传导到实体上
// ——上层拿到一个非零的 Expense.支出币种，不必再校验一次它是否为已知币种。
//
// # 为什么不用裸 string：四个类型来源
//
//	枚举类字段  currency.Code / enum.*        角色、状态、币种、格式、解析器键、审计三枚举
//	金额与汇率  base/decimal.Decimal          支出金额、折算汇率、本位币金额
//	日期与年月  base/calendar.Date / .Month   支出日期、摊分起止月
//	标识        int64                         5 类实体标识与 3 处引用（idgen 的返回类型）
//
// 裸 string 只出现在**三类确实没有取值域的字段**上，逐类可追溯：
//
//   - **自由文本**：用户名、密码哈希、盐、交易对手方、交易备注、银行名称、
//     卡号后四位、原始文件名、内容校验值、文件密码、操作摘要、变更内容。
//     它们没有枚举可言，取值由用户输入或账单解析决定。
//   - **界面语言**：终版 §四 1 定义它是「语言配置文件的键」，而语言集由 i18n
//     持有——i18n 在 L3，本包 import 它必成环（分层 §七 依赖图 L11 → L10 → L0，
//     无 L1.1 → L3 的边）。故本字段是全包唯一「本该有取值域却只能用 string」的
//     字段，合法性由 service/preference 调 i18n 的语言键校验兜住（分层 §六 L5.4）。
//     这不是遗漏，是依赖方向的必然结果，已登记在 answer 的待确认项中。
//   - **卡号后四位**：形似数字实为文本。若用整数，「0012」会静默变成 12——
//     卡号后四位是 F-4 的筛选维度，位数丢了就筛不出那张卡。
//
// # 零值即「不适用」：全包无一个指针字段
//
// 终版 §四 表头定义「「必填」= 任何记录都必须有确定值；业务上「不适用」的场景以
// 零值表达，不留空」。因此 8 个可空属性（Expense 的交易对手方 / 交易备注 /
// 支出类型ID / 来源文件ID / 银行名称 / 卡号后四位 / 卡片币种 / 删除时间，
// 以及 File 的文件密码）**一律用零值而非指针**表达「无」。
//
// 这条选择有实质收益：0 与 nil 在 Go 里的区别是「取值前是否必须判空」。62 个字段
// 全部是值类型后，任何字段都可在零值实体上直接访问而不 panic，`var e Expense` 即
// 是一个可用的空明细——D-4 预览页的手工录入行、F-8 复制的初值都从这里起步。
// 反过来若用指针，每个消费方都要写一遍判空，而漏写不会报错，只会在某条没有对手方
// 的明细上突然崩掉。
//
// 唯一的例外由类型自身携带：File.文件内容 是 []byte，其 nil 与空切片的区别另有
// 语义（见 File.Content 的注释），不属于本条。
//
// # 三样刻意不做
//
//  1. **不加 db / gorm 等存储标签**。分层 §六 L4 明写 store/sqlite 是「唯一知道
//     SQL 的地方」，列名、列类型与 NULL 口径都归它。在本包写列名等于把存储选型
//     的知识提前到 L1.1，换存储引擎（分层 §十二「换/加存储引擎」）时就得改 L1.1。
//  2. **不加 json 标签、不是 JSON 契约**。分层 §六 L6 定死「dto **不复用 entity
//     结构体**，只做单向字段裁剪与转换」——前提 6 正是靠「只读派生字段在写请求
//     dto 里根本不存在」守住的，若 entity 兼作契约，那道闸门当场失效。
//     **唯一例外是 User 的密码哈希与盐上的 `json:"-"`**，它是密码红线的兜底而不是
//     契约声明，理由见该字段注释。
//  3. **不定义 Expenses []Expense 这类集合类型**。集合类型的价值在于挂方法
//     （排序、过滤），而本包零方法，定义它只是多一个别名；排序归 store 的
//     ORDER BY（F-3）、筛选归 store 的查询条件（F-4），都不在内存里做。
//
// # 依赖边界
//
// 本包恰好 import 4 个仓库内包 + 标准库 time：currency、enum、base/decimal、
// base/calendar，与分层 §六 L1.1 的依赖列逐字一致。特别地**不依赖 base/errs**
// （零方法即无错误可返）、**不依赖 base/idgen**（标识由 service 层生成后赋值，
// 本包只声明 int64 字段），也不依赖任何 L2 及以上的包——由
// TestDependencyBoundary 以 AST 扫描锁死。
//
// # 已登记的残留：%+v 会打出密码哈希与盐
//
// 零方法约束使本包无法像 base/config 那样用 String() 做脱敏，因此
// `fmt.Sprintf("%+v", user)` 或 `logrus.Fields{"user": user}` 会把密码哈希与盐
// 打进日志。JSON 一侧已由 `json:"-"` 兜住，日志一侧无编译期兜底，只能靠约定：
// **L5 与 L6 一律不整体打印 entity.User，需要时只打用户ID 与用户名**。
// 这与分层 §四 的 R1/R2/R3 同类——Go 的机制修不掉，登记后靠评审守住。
