package entity

import (
	"time"

	"github.com/cellargalaxy/jotcash/internal/enum"
)

// AuditLog 是操作审计，承载终版 §四 5 的 9 项属性，**全部必填**。
//
// 它是**留痕与批次追溯的枢纽**（终版 §三）：操作审计是全系统唯一的留痕机制
// （前提 4，不另建导入批次表、修改历史表），而**一次提交 = 一条审计 = 一个可追溯
// 批次**（不变式 4）。
//
// # 无删除标记、无回滚字段
//
// 前提 8 把 AuditLog 列为「一律不可删除」的三个实体之一，故无 DeletedAt。
//
// 终版 §四 5 表下注另明写「**无「回滚审计ID」**——批次撤销已下沉为明细列表页的
// 批量删除，重复删除由「已删除跳过」天然幂等，不需要状态位」。这是对话13 → 终版的
// 实质变化之一（§十二：属性 63 → 62，审计枚举 12 → 11 类，「回滚」项删除）。
// 若此处出现 RollbackAuditID，就等于把已作废的 D-8 又加回来了。
//
// # 写入方恰 9 个 service，且 service/audit 是唯一实现处
//
// 不变式 4 的唯一实现处是 service/audit（分层 §九），**禁止任何 service 直接写
// AuditLog 表**——该约束无编译期兜底（分层 §四 R1），靠准则 5 与评审守住。
// 11 类操作类型的写入方一一对应到 9 个 service（分层 §九 末段）：
// account（1/3/4）、auth（2）、file（5）、intake（6）、expense（7）、fx（8）、
// category（9）、preference（10）、export（11）。
//
// 两种写入语义（分层 §六 L5.0）：业务同事务审计走「先落审计取 ID → 业务数据挂载
// 该 ID → 同事务提交」，审计ID 由 base/idgen 生成、**不依赖自增回填**（约定 9）；
// Result = 失败 的记录走独立事务，业务回滚不带走它。
type AuditLog struct {
	// ID 审计ID，唯一标识，**兼「入库批次号」**（终版 §四 5）。
	//
	// 由 base/idgen.GenAuditID() 生成，唯一调用方 service/audit。它在事务提交前
	// 就已确定，因此 Expense.SourceAuditID 与 File.SourceAuditID 可在同一事务内
	// 挂载，无需数据库回传（约定 9 / 不变式 4）。
	ID int64

	// UserID **操作人**，同时是数据归属人（终版 §四 5）。
	//
	// # 登录失败记录中的语义例外
	//
	// 终版 §四 5 明写：「**登录失败记录中它表示被尝试账号的归属，不代表操作人
	// 身份**（尝试者不可知，不留字段）」。配套规则在 8.4 第 2 类：用户名**存在**
	// （含密码错、账户禁用、锁定期内）则记录并归属该用户，用户名**不存在**则
	// **不记审计**（无归属、无消费方）。
	//
	// 另一处需注意：管理员对他人账户的操作**归属管理员**，被操作者在 K-2 中看不到
	// ——依前提 3 显式接受，不建被动审计副本（B-4 边界③）。
	//
	// 字段名不叫 OwnerUserID 而叫 UserID，正是因为它在登录失败这一类里不是纯粹的
	// 「归属」，与另外 3 个实体的 OwnerUserID 语义不完全等同。
	UserID int64

	// Type 操作类型，**11 类枚举**（终版 §四 5 / 8.4）。
	//
	// 三个刻意缺席：登出（A-4 明写「登出为前端丢弃令牌，服务端无动作、不记审计」）、
	// 明细新增（8.4 表下注：「明细的「新增」不在本表单列——一律走「数据入库」」）、
	// 回滚（§十二 D-8 整项取消）。项数与集合已由 enum 的 TestOperationTypeCodes
	// 与 TestOperationTypeExcludedItems 锁死。
	Type enum.OperationType

	// ObjectType 操作对象类型，**零值 = 本次操作无具体对象或为批量操作**
	// （终版 §四 5）。
	//
	// 这是全模型唯一一处「零值是合法业务取值」的枚举字段：11 类审计中有 5 类
	// （登录 / 数据入库 / 批量删除 / 本位币重算 / 数据导出）就该落零值。
	// 因此 enum 的 Value() 对零值返回**空串而非 NULL**——§四 5 表头明写 9 项
	// 「全部必填」，落 NULL 会被 NOT NULL 约束当场拒绝掉一个合法的零值。
	// 判定应写 `t.IsZero() || t.Valid()`，不能只写 Valid()。
	ObjectType enum.ObjectType

	// ObjectID 对象ID，零值 = 同 ObjectType；**是历史指针，不是外键**——指向的
	// 对象可能已被删除（终版 §四 5）。
	//
	// 「历史指针」有两处实际后果（K-2）：跳转目标为**已软删除的明细**时正常跳转
	// 并自动带上「显示已删除」筛选（记录仍在）；仅**已被物理删除的支出类型**降级为
	// 「该对象已删除」提示。因此本字段不建立外键约束，也不参与终版 §七 的 5 组
	// 关联关系（§七 末句明写）。
	ObjectID int64

	// Summary 操作摘要，人可读描述，如「导入 37 笔，合计 1,204.50 CNY」
	// 「批量删除 12 笔（来源审计 #88）」（终版 §四 5）。
	//
	// 四处对摘要有硬要求：8.4 第 9 类「支出类型维护」的摘要**必须带类型名称**
	// （物理删除后审计仍可读的唯一保障）；第 7 类批量删除的摘要**记筛选条件与
	// 实际笔数**（对象ID 为零值时的唯一线索）；第 11 类记范围与笔数；
	// F-8 复制提交的摘要记「复制自明细 X」（8.5）。
	//
	// 它是**已知代价②**的兜底（终版 §十二）：无「删除审计ID」，从一条已删除明细
	// 正向反查「是哪次操作删的」做不到，反向只能靠本字段的内容查到。
	Summary string

	// Changes 变更内容，编辑类操作的前后值快照；零值 = 非编辑类操作；
	// **一律不记任何密码值（明文、哈希、盐）**（终版 §四 5 / B-4 边界②）。
	//
	// 用 string 而非结构化类型：本字段的形态由各业务服务自行采集（分层 §六 L5.0：
	// 「变更内容 由各业务服务采集」，service/audit 只负责落库并强制过滤密码值），
	// 且 K-2 只读、不做按字段检索。在 L1.1 定死结构会限制 7 类编辑操作各自的
	// 快照形态，而它们的字段集本就不同。
	Changes string

	// Result 操作结果，成功 / 失败（终版 §四 5）。
	//
	// 恰两项，无「部分成功」——I-7 允许部分失败（不变式 2：重算的原子粒度是单笔），
	// 其部分失败由 Summary 记「成功/失败笔数」表达，不占本枚举一项。
	// 失败记录走 service/audit 的独立事务语义，业务回滚不带走它。
	Result enum.OperationResult

	// Time 操作时间，发生时点（终版 §四 5）。
	//
	// 字段名不叫 CreatedAt：本实体不可修改也不可删除，只有「发生」这一个时点，
	// 终版 §四 5 的 9 项里就是这一个时间戳，无创建/更新之分。
	Time time.Time
}
