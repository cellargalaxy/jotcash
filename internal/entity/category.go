package entity

import (
	"time"
)

// ExpenseCategory 是支出类型，承载终版 §四 2 的 5 项属性，**全部必填**。
//
// # 全模型唯一支持物理删除的实体
//
// 终版前提 8 定义全模型只有两种删除：Expense 的软删除与本实体的**物理删除**
// （仅限无引用时，删即不可恢复）。因此本结构体**无 DeletedAt 字段**——删了就
// 不在库里了，没有标记可写。
//
// 连带后果有两处，都不在本包但由本实体的形态决定：
//
//   - AuditLog.ObjectID 指向本实体时是**历史指针而非外键**，删除后 K-2 降级为
//     「该对象已删除」提示——这是**全模型唯一会触发该提示的对象**（终版 K-2）。
//     故 8.4 第 9 类审计的摘要**必须带类型名称**，那是物理删除后审计仍可读的
//     唯一保障（分层 §六 L5.1 category 行）。
//   - G-4 的引用检查必须**与删除同事务**，否则 TOCTOU：检查通过后、删除前恰有
//     一笔明细引用了它（分层 §六 L5.1 category 行明写）。
//
// # 无状态字段
//
// 终版 §四 2 表下注明写「无状态字段——不提供停用；生命周期只有「新建」与
// 「无引用时物理删除」两态」。G-1 亦明写「只能新建与删除（不提供改名，也不提供
// 停用）」。故本结构体既无 Status 也无 Enabled——这与 currency / enum 的枚举项
// 「只能停用不能删除」恰好相反，因为那两者的历史值存在明细里，而本实体的引用
// 关系可被检查（G-4）。
//
// 已登记的代价（终版 §十二 已知代价③）：**类型一旦被任何明细（含已软删除）引用
// 即永久不可删除**——已删除明细只读、其类型不可改，系统又无停用能力且下拉恒含
// 全部类型，废弃类型无清理手段。这是显式接受的取舍，不是本包能修的。
type ExpenseCategory struct {
	// ID 类型ID，唯一标识（终版 §四 2）。
	//
	// 由 base/idgen.GenCategoryID() 生成，唯一调用方 service/category（G-1 新建）。
	ID int64

	// OwnerUserID 归属用户ID。用户级字典，各用户互不可见；**开户时为空集**
	// （终版 §四 2 / G-1）。
	//
	// 「开户时为空集」意味着 A-1 与 A-7 创建账户时不预置任何类型，全部由用户自建
	// （G-1）；也意味着 F-4 / F-5 的类型下拉在新账户上是空的，这是设计内状态。
	OwnerUserID int64

	// Name 名称。单层无父子，全部由用户自建，**同一用户下唯一**；不提供改名、
	// 不做多语翻译（终版 §四 2 / G-1 / K-4）。
	//
	// 唯一性口径是 **(归属用户ID, 名称)** 复合唯一，由存储层唯一索引保证而非
	// 先查后插（分层 §六 L3 store ⑤、准则 6）；冲突映射到 base/errs 的
	// 「唯一冲突」档（对应 HTTP 409）。
	//
	// 不做多语翻译：K-4 明写多语言「不含数据内容（支出类型名称等）的翻译」，
	// 故本字段是纯数据而非文案键，与 currency.Code.NameKey() 的取向相反。
	Name string

	// CreatedAt 创建时间（终版 §四 2）。
	CreatedAt time.Time

	// UpdatedAt 更新时间（终版 §四 2）。
	//
	// 本实体不提供改名也不提供停用，因此本字段实际上恒等于 CreatedAt。
	// 仍然保留：终版 §四 2 把它明列为 5 项属性之一，属性点算（62 项）依赖它；
	// 且删掉它会让 5 个实体的时间戳字段形态不一致。
	UpdatedAt time.Time
}
