package entity

import (
	"time"

	"github.com/cellargalaxy/jotcash/internal/base/calendar"
	"github.com/cellargalaxy/jotcash/internal/base/decimal"
	"github.com/cellargalaxy/jotcash/internal/currency"
)

// Expense 是支出明细，承载终版 §四 3 的 22 项属性，是**唯一的事实实体**
// （终版 §三：摊分份额不落库、卡片不建实体、汇率不建实体）。
//
// # 22 项按可写性分三组，字段顺序即分组顺序
//
//	用户可编辑  8 项  终版 F-1        D-7 提交与 F-5 保存的可写字段全集
//	只读派生    4 项  终版 §四 3      由 rule/convert 与 rule/amortize 算出
//	系统只读   10 项  终版 §四 3      由 service 层在创建时写入，之后不可改
//
// 8 + 4 + 10 = 22，与 F-1(8) + F-2(14) = 22 两向一致（终版 §十二 校验方式②）。
// 分组不是注释上的装饰：**前提 6 与不变式 1 的边界恰好落在这三组之间**——
// 第二组的 4 项在 api/http/dto 的写请求结构里根本不存在（分层 §九 前提 6 行：
// 「结构缺席 > 运行时忽略」），第三组的 10 项连响应外的任何入口都没有。
//
// # 两条不变式在本实体上的形态
//
//	不变式 1a  BaseAmount = Amount × Rate 恒成立，且 BaseCurrency 仅在
//	           「汇率按当前本位币重拉或用户手填」时更新（终版 8.1 六种触发）
//	不变式 1b  AmortizeStart = 支出日期所属月；AmortizeEnd = 起始月 + 月数 − 1
//
// 两者都**不在本包实现**（零方法，见包注释）：1a 归 rule/convert、1b 归
// rule/amortize，且终版 8.1 第 3 行「改支出日期」会同时触发两者，故
// service/expense 与 service/intake 必须在同一次保存内一并调用（分层 §九 不变式 1b 行）。
//
// # 软删除是终态
//
// DeletedAt 有值即已删除（终版前提 8 / 8.5），**无恢复入口**，找回一律靠 F-8
// 复制为新明细。已删除行的五条行为互不抵触（终版 §十二 校验方式⑨）：
// 只读（F-5 仅对未删除开放）+ 可查看（F-4 显示已删除）+ 可复制（F-8）+
// 参与 I-7 重算 + 不参与 J 域统计。
type Expense struct {
	// ---- 用户可编辑（8 项，终版 F-1） ----

	// SpendDate 支出日期，必填。交易发生日；未摊分口径的归月依据，也是取日汇率
	// 的依据；**字面值，无时区换算**（终版 §四 3 / 前提 7）。
	//
	// 用 calendar.Date 而非 time.Time：前提 7 的唯一实现处是该类型（分层 §九
	// 前提 7 行）。若用 time.Time，同一字面值在不同时区下取到的所属月会整体偏移
	// 一天，摊分起始月、J-1 归月、I-4 取日汇率三处同时静默出错。
	SpendDate calendar.Date

	// Amount 支出金额，必填。原币金额，**允许为负**（退款、冲正，终版 §四 3）。
	//
	// 负金额的摊分规则完全对称，从退款发生月起摊、不改写历史月份（终版 H-2）。
	Amount decimal.Decimal

	// Currency 支出币种，必填，币种枚举代码（终版 §四 3）。
	//
	// 取值域是**全部启用币种**，不受 T38 的本位币候选口径限制——分层 §六 L1.0
	// 明写「支出币种不受此限（3 位币种仍可正常记账与摊分）」。
	// 它同时是 8.2 摊分中「原币按支出币种小数位数均分」的基准。
	Currency currency.Code

	// Counterparty 交易对手方，**非必填**。商户或收款方；账单未给出时留空
	// （终版 §四 3）。F-4 的模糊筛选维度之一。
	Counterparty string

	// Remark 交易备注，**非必填**。账单摘要或用户自填；未给出时留空
	// （终版 §四 3）。F-4 的模糊筛选维度之一。
	Remark string

	// CategoryID 支出类型ID，**非必填**，**零值即未分类**（终版 §四 3 / G-2）。
	//
	// 字典中不设「未分类」记录（G-2），F-4 的类型多选中「空」即代表未分类。
	// 引用 ExpenseCategory.ID；注意 G-4：**已软删除的明细同样构成引用**，
	// 因此被本字段指向的类型永久不可物理删除（终版 §十二 已知代价③）。
	//
	// 零值而非指针：终版 §四 表头「不适用的场景以零值表达，不留空」，
	// 且 base/idgen 保证 ID 恒为正，故 0 可安全表示「无」（idgen.IsValid 是其判据）。
	CategoryID int64

	// AmortizeMonths 摊分月数，必填，**默认 1**（不摊分），**不设上限**
	// （终版 §四 3 / H-1 / 前提 5）。
	//
	// 用 int 而非 decimal：它是份数，参与运算时由 rule/amortize 转成
	// decimal.FromInt 作除数（后者对零返回 ErrDivideByZero，而非 panic——
	// 本字段来自用户输入，一次非法输入不应崩掉请求）。
	AmortizeMonths int

	// Rate 折算汇率，必填。1 单位原币可兑换的本位币数量；原币 = 本位币时取 1；
	// 自动获取失败时必填（终版 §四 3 / I-5）。
	//
	// **8 位小数**（T39），规整点唯一：rule/convert 在做乘法前把入参规整到
	// decimal.RateScale，其输出三元组中的汇率即规整后的值，落库以它为准。
	// 自动获取（fxrate 返回值精度不设限）与 I-5 用户手填两条入口共用该规整点，
	// 因此不会出现「库里存 12 位、算的时候用 8 位」。
	//
	// I-5 明写重拉失败时该行汇率转必填、未填不可提交 / 不可保存，
	// **不静默按 1:1 处理**——零值在此是「未填」而非「1」，判据在 service/fx。
	Rate decimal.Decimal

	// ---- 只读派生（4 项，全部必填，终版 §四 3） ----
	//
	// 这 4 项在 api/http/dto 的写请求结构里**根本不定义**（分层 §九 前提 6 行），
	// service/expense 与 service/intake 一律以 rule/convert / rule/amortize 的
	// 输出覆盖它们，**不接受任何上游传入值**。

	// BaseAmount 本位币金额，**= Amount × Rate**，无人工指定入口（终版前提 6 / §四 3）。
	//
	// 只读因变量：任何一次编辑后立即由 rule/convert 重算（不变式 1a）。
	// 两层精度口径不可混为一谈——**算**按本位币的 currency.Scale() 四舍五入
	// （T38 保证 ≤ 2 位），**存**为 decimal.BaseAmountStoreScale（2 位定点），
	// 0/1/2 位的算出结果必然能被 2 位列无损容纳。
	BaseAmount decimal.Decimal

	// BaseCurrency 折算本位币币种，必填。折算当时的本位币（终版 §四 3）。
	//
	// **≠ User.BaseCurrency 即待重算 / 重算失败**——这是判断该行是否已按当前
	// 本位币折算的**唯一依据**，也是 I-7 重算时「跳过」与 F-4 筛选时「识别未收敛
	// 行」的同一个判据（不变式 2）。
	//
	// 与汇率、本位币金额三者联动（终版 8.1）：只要汇率是「按当前本位币重新拉的」
	// 或「用户手填的」，本字段就一并改为当前本位币；**只有「只改金额、汇率没动」
	// 这一种不改它**。否则手工兜底的行永远收敛不了，且会被下一次 I-7 覆盖掉手填值。
	BaseCurrency currency.Code

	// AmortizeStart 摊分起始月，必填。= 支出日期所属月（终版 §四 3 / 8.2）。
	AmortizeStart calendar.Month

	// AmortizeEnd 摊分结束月，必填。= 起始月 + 摊分月数 − 1（终版 §四 3 / 8.2）。
	//
	// 它与 AmortizeStart 是 J 域摊分口径**区间穿刺**（起始月 ≤ M 且 结束月 ≥ M）
	// 的两个端点。终版 8.2 明写不建聚合表：两个条件是合取且各自具备选择性——
	// 查近期月份时后者排除掉早已摊完的绝大多数支出，查久远月份时前者排除掉该月
	// 之后发生的全部支出。calendar.Month 的定长文本形态使这两个条件可走索引。
	AmortizeEnd calendar.Month

	// ---- 系统只读（10 项，终版 §四 3） ----

	// ID 明细ID，必填，唯一标识。
	//
	// 由 base/idgen.GenExpenseID() 生成，唯一调用方是 service/intake——
	// D-7 提交入库时为每条原始交易行生成，F-8 复制走同一条入库链路；
	// **F-5 逐笔编辑不生成新 ID**。
	ID int64

	// OwnerUserID 归属用户ID，必填。数据归属（终版 §四 3 / B-1）。
	//
	// 不变式 3「归属校验无死角」的载体：store 的 Expense 仓储每个按 ID 访问的
	// 方法签名强制带归属用户ID，且**该参数对任何角色一律生效、无管理员旁路**
	// （前提 3）。漏一处等于全量泄露（分层 §九 不变式 3 行）。
	OwnerUserID int64

	// SourceAuditID 来源审计ID，必填。属于哪次入库，**批次筛选与撤销以此为单位**
	// （终版 §四 3 / 不变式 4）。
	//
	// 挂的是「数据入库」那条审计（8.4 第 6 类）。F-5 编辑**不改本字段**
	// （终版 F-5），F-8 复制则挂到本次复制提交产生的**新审计**上（8.5 复制字段表）。
	// 一次提交 = 一条审计 = 一个可追溯批次，K-2 跳转带「来源审计 = 该ID」的筛选
	// 条件即批次撤销的唯一入口（K-2 / §十 流程 5）。
	SourceAuditID int64

	// SourceFileID 来源文件ID，**非必填**。从哪个文件解析而来；**手工录入时为零值；
	// 复制时继承被复制明细的值**（终版 §四 3 / 8.5）。
	SourceFileID int64

	// BankName 银行名称，**非必填**。卡片来源标识，解析所得；解析不出时留空；
	// 复制时继承（终版 §四 3）。
	//
	// 终版 §六 刻意不建「银行卡片档案」实体，替代方案即本字段与下面两项——
	// 三者是明细上的值，不是引用（终版 §七 末句）。F-4 支持按它筛选并含
	// 「未识别」选项，那个选项对应的就是本字段为空串。
	BankName string

	// CardLast4 卡号后四位，**非必填**。同 BankName（终版 §四 3）。
	//
	// 用 string 而非整数：卡号后四位形似数字实为文本，「0012」若用整数会静默
	// 变成 12，而它是 F-4 的筛选维度，位数丢了就筛不出那张卡。
	CardLast4 string

	// CardCurrency 卡片币种，**非必填**，币种枚举代码（终版 §四 3）。
	//
	// 解析不出则留空，故零值在此是合法业务取值——currency.Code 的零值落库为
	// NULL、序列化为 null，正是为这类可空场景设计的。
	CardCurrency currency.Code

	// DeletedAt 删除时间，**非必填**。**有值即已删除**（软删除），**终态不可逆**，
	// 无恢复入口（终版 §四 3 / 前提 8）。
	//
	// 批量删除时**已删除行跳过、不覆盖其原值**（终版 F-8 / 8.5），删除因此天然
	// 幂等、失败重跑即可。零值 = 未删除，是 F-4 默认视图与 J 域统计的过滤判据。
	//
	// 用 time.Time 而非 calendar.Date：它是业务时间戳而非账单字面日期，
	// 不受前提 7 约束（分层 §九 前提 7 行末句）。
	DeletedAt time.Time

	// CreatedAt 创建时间，必填（终版 §四 3）。
	CreatedAt time.Time

	// UpdatedAt 更新时间，必填（终版 §四 3）。
	UpdatedAt time.Time
}
