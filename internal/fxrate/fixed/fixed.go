// Package fixed 是一个**占位汇率源实现**（L4 适配实现层），恒返回汇率 1。
//
// # 它为什么存在
//
// 汇率源尚未选定。这不是遗漏而是被登记过的挂起项：分层 §六 L4 写明
// 「`fxrate/<源>` 的具体包名随汇率源选定后确定」，§四 亦记「fxrate/<源> 的具体
// 包名随汇率源选定后确定，不影响分层」；configs/jotcash.example.yaml 的
// fx_rate_endpoint / fx_rate_secret 两项当前留空并注明「汇率源尚未选定」；
// currency.RateSourceDefault 的注释同样写着「本轮先定机制不定取值域」。
//
// 本轮 prompt 明确要求：「具体查询汇率的外部调用接口依然挂起，汇率先直接在代码里
// 写死返回 1，待之后再进行改造」。本包即该要求的落点。
//
// 把写死的 1 放在 L4 而不是端口里，是因为**这是一个选型**（一个「暂不接外部源」
// 的选型），而分层 准则 4 规定「端口在下、实现在上……换选型 = 加平级子包 + 改
// app 一行」。选定真实汇率源那天，动作是「加 fxrate/<真实源> 平级子包 + 改 app
// 一行装配」，本包连同这行注释一起删除，**fxrate 端口与 L5 一行不改**。
// 若把 1 写在端口里，那一天要改的就是所有人都依赖的那一层。
//
// # 恒返回 1 与 I-5「禁止静默 1:1」是两回事
//
// 这是本包最需要讲清的一点，因为二者数值相同。
//
// 终版 I-5 禁止的是「**自动获取或重拉失败时**……静默按 1:1 处理」——被禁止的是
// **用 1 掩盖一次失败**，关键词是「失败」与「静默」。本包不掩盖任何失败：它压根
// 没有去取汇率，返回的 1 是一个**显式配置的占位值**，且这件事在四个地方写着：
//
//	① 包名就叫 fixed，导入路径 internal/fxrate/fixed 出现在 app 的装配代码里
//	② New 在构造时打一条 Warn 级日志（每进程一次，见 New）
//	③ Fetcher.Note() 返回一句说明，供 app 写进启动日志
//	④ 本包属 L4，按约定 2「实现子包只被 app import」，必须由 app 显式注册才生效
//
// 反过来说，一旦接入真实汇率源，那个实现**必须**遵守 fxrate.Fetcher 契约第 1 条
// ——失败时返回错误而不是 1，由 service/fx 走 I-5 让用户手填。本包不是那条规则的
// 例外，它是「规则尚未有对象可管」的临时状态。
//
// # 已知代价（本轮显式接受）
//
// 在真实汇率源接入之前，本位币金额恒等于支出金额的数值：
//
//   - 支出币种 = 本位币时**结果正确**（I-4 短路本就取 1，且 service/fx 会短路掉、
//     根本不调本包）；
//   - 支出币种 ≠ 本位币时**结果不正确**——一笔 100 USD 的支出在 CNY 本位币下会被
//     记成 100 CNY。用户可经 I-5 手填汇率纠正（折算汇率是 F-1 的八个可编辑字段
//     之一），或在接入真实源后由 I-7 逐笔重算一次性收敛。
//
// 后一条正是 I-7 存在的意义，因此这个代价是**可回收**的：换源后跑一次 I-7，
// 全部明细按真实汇率重算，不需要数据迁移。
//
// # 不做什么
//
//   - **不发 HTTP、不读配置**。端点与密钥（base/config 的 FxRateEndpoint /
//     FxRateSecret）留给真实实现，本包不接收任何注入参数。
//   - **不做日汇率缓存**。L4 承载里的「同日同币种对只取一次」是给真实源的：
//     本包没有外部调用，缓存一个常量没有意义。
//   - **不区分币种对、不区分日期**。任何合法 Query 都得 1。
//   - **不规整精度**（T39：规整点唯一，在 rule/convert）。1 本身是 0 位小数，
//     经 decimal.RoundRate 规整仍是 1，不受影响。
//
// # 依赖边界
//
// 依赖恰为 fxrate（L3 端口）与 base/decimal（L0），外加日志所需的 logrus。
// 与分层 §六 L4 表 fxrate/<源> 行的依赖列「fxrate」一致。本包处于 L4，
// **只被 app import**（约定 2），不得被 L5 及以下引用——否则业务层就绑上了选型。
//
// # 并发
//
// Fetcher 是不可变值类型（无字段），Fetch 无状态、无 IO，可并发使用。
package fixed

import (
	"context"

	"github.com/cellargalaxy/jotcash/internal/base/decimal"
	"github.com/cellargalaxy/jotcash/internal/fxrate"
	"github.com/sirupsen/logrus"
)

// Rate 是本占位实现恒定返回的汇率值：1。
//
// 导出是为了让 app 的启动日志与测试能引用同一个来源，而不是各写一遍字面量 1。
//
// 用 decimal.FromInt(1) 而不是 decimal.MustParse("1")：两者结果相同，
// 但前者不经文本解析，包初始化时不可能失败。
var Rate = decimal.FromInt(1)

// Note 是本实现的性质说明，供 app 写进启动日志、也供运维在排查
// 「为什么本位币金额等于支出金额」时一眼看到原因。
//
// 导出为常量而非写死在日志语句里：app 与本包的构造日志引用同一份文本，
// 不会出现两处描述不一致。
const Note = "占位汇率源：恒返回汇率 1，未接入任何外部汇率源；" +
	"跨币种明细的本位币金额不正确，接入真实汇率源后需执行一次 I-7 逐笔重算"

// Fetcher 是恒返回汇率 1 的 fxrate.Fetcher 实现。
//
// 空结构体：本实现没有任何状态、没有配置、没有连接。零值可用，但**应当经 New
// 构造**——那条构造日志是本包「不静默」的主要保障（见包注释）。
type Fetcher struct{}

// 编译期断言：本类型必须满足端口接口。
// 放在这里而不是靠 app 的赋值发现：接口若在 L3 变更，本包应当**第一时间**编译失败，
// 而不是等到 app 那一层才报错——那时错误信息指向的是装配代码，不是实现本身。
var _ fxrate.Fetcher = Fetcher{}

// New 构造占位汇率源，并打一条 Warn 级日志。
//
// # 为什么构造时一定要打日志
//
// 这是本包与 I-5「静默 1:1」之间**唯一的行为差别**（数值上二者完全相同），
// 因此不能省。它必须满足两条：
//
//   - **Warn 级**而非 Info：Info 在生产日志里会被淹没，而这条信息在「用户报告
//     金额不对」时是第一现场。它也不该是 Error——占位实现在当前阶段是预期状态，
//     不是故障，用 Error 会污染告警。
//   - **每进程一次**，不是每笔一次。Fetch 里不打任何日志：I-7 逐笔重算会以每笔
//     明细一次的频率调用它，在那里打日志就是几万行重复记录，真正的根因反而被
//     淹没（同 fxrate 端口包注释「不打日志」）。
//
// ctx 只用于让日志带上请求上下文（go_common 的 logrus hook 从 ctx 取链路字段），
// 本函数不会因 ctx 取消而失败——构造一个无状态实现没有可取消的动作。
//
// 恒成功，无错误返回值：本实现没有任何可能失败的构造步骤（无连接、无配置解析）。
// 加一个恒为 nil 的 error 只会让 app 写一个永远不会进的分支。
func New(ctx context.Context) Fetcher {
	logrus.WithContext(ctx).WithFields(logrus.Fields{
		"rate": Rate.String(),
		"note": Note,
	}).Warn("汇率源，使用占位实现")
	return Fetcher{}
}

// Fetch 恒返回汇率 1，满足 fxrate.Fetcher。
//
// 入参 q 已由 fxrate.Registry.Fetch 校验过三个字段非零值，本实现**不重复校验**
// ——端口已经做过的事在实现里再做一遍，只会让两处判据将来分叉。
//
// 不区分币种对、不区分日期：任何合法 Query 都得 1，这正是「占位」的含义。
//
// # 唯一的失败路径是 ctx 已取消
//
// 保留这条分支是为了满足 fxrate.Fetcher 契约第 4 条所要的可中断性：终版 I-7
// 明写重算「可中断可续跑」，若本实现无视 ctx，一次中断要等到全部明细跑完才生效。
//
// 返回的是**原始的 context 错误**（context.Canceled / DeadlineExceeded），
// 不包装成本包的错误：Registry.Fetch 会把它包进 fxrate.ErrFetch，而 errors.Is
// 对两者同时成立，service/fx 因此能先判 context.Canceled 决定「整批停下」，
// 而不是把一次中断误判成 I-5 的「该行汇率转必填」（那会把中断变成用户面前的
// 表单故障）。
//
// 除此之外**没有任何失败路径**，也就没有任何「失败了却返回 1」的可能——
// 本实现返回的 1 恒是占位值，不是对失败的掩盖（见包注释）。
func (Fetcher) Fetch(ctx context.Context, q fxrate.Query) (decimal.Decimal, error) {
	//先判取消：I-7 是可中断批处理，无视 ctx 会让中断要等到整批跑完才生效
	if err := ctx.Err(); err != nil {
		return decimal.Decimal{}, err
	}
	//不打日志：I-7 逐笔调用，在此打日志即每笔一行（见 New 的注释）
	return Rate, nil
}

// Note 返回本实现的性质说明。
//
// 供 app 在启动日志里记录「当前用的是哪个汇率源、它是什么性质」，
// 无需 app 自己 import 本包的常量再拼一遍。
func (Fetcher) Note() string { return Note }
