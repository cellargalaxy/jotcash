// Package parser 是账单解析的**端口层**：只定义解析器接口、原始交易行结构与
// 按解析器类型键的注册表，不含任何具体格式的解析实现。
//
// 承载自分层 §六 L3 表 parser 行：
//
//	解析器接口（入参含文件内容与文件密码，D-2）+「原始交易行」结构（支出日期/
//	金额/币种/对手方/备注 + 银行名称/卡号后四位/卡片币种，解析不出则留空）+
//	按解析器类型键的注册表（D-1）；错误分类：格式不符 / 内容损坏 / 字段缺失 /
//	解密失败 / 类型不匹配（D-3），一律返回带文案键的 base/errs。
//	不依赖 entity——原始行到 entity.Expense 的映射归 service/intake
//
// # 为什么要有这一层
//
// D-1 定死了扩展方式：「**适配各银行原生导出格式**，不定义统一的导入模板」，
// 且「格式不足以判定解析器——同为 PDF，各银行版式不同」，因此解析器类型由用户
// 在上传页显式选择（D-2）。于是新增一家银行 = 新增一个 L4 平级子包 + 在 app
// 里多注册一项，**上层一行不改**。这条性质要靠「接口在下、实现在上」来保证
// （准则 4）：本包不 import 任何 parser/xxx 子包，也不 import encoding/csv
// 这类具体格式的词法库——那会把「CSV」这一选型固化进端口层。
//
// # 本包不做什么
//
//   - **不做任何解析**。CSV 实现是 parser/csv（L4，阶段 6），PDF 同理。
//     分层 §十一 阶段 4 对本包的完成标志是「只有接口、类型与注册表，可编译」。
//   - **不 import entity**。承载末句明写，原始行到 entity.Expense 的映射归
//     service/intake。本包连 entity.Expense 的字段名都不该知道，只知道自己
//     那 8 个字段。TestDependencyBoundary 双向锁死这条。
//   - **不做业务必填校验**。RawRow 全部字段零值合法（见该类型注释），必填性
//     由各 L4 实现按自己的账单版式判定——只有它知道「该列在第几列、空了算不算
//     缺」，也只有它能给出 D-3 要求的行号与列名。本包提供的是让所有实现产出
//     **形状一致**的错误的工具（见 errors.go），统一的是错误形状，不是校验位置。
//   - **不猜四个派生字段**。RawRow 刻意不含 摊分月数 / 折算汇率 / 本位币金额 /
//     支出类型，理由见 RawRow 的注释「为什么恰是这 8 个字段」。
//   - **不碰文件密码之外的凭据**，也不打印密码（见 Input.Password）。
//
// # D-3 五类错误的边界：按「判断层级」划界，不靠语感
//
// 五类的名字两两之间很容易混（「格式不符」与「内容损坏」尤甚）。本包按
// **做出判断所处的层级**划界，errors.go 的分类器与 errors_test.go 的穷举
// 用例都以此为准：
//
//	类型不匹配 type_mismatch   文件 × 用户选择   ParserType.Format() != File.Format
//	解密失败   decrypt_failed  文件整体         口令错或未提供
//	格式不符   format_mismatch 文件版式         表头/列数/分隔符不符合该解析器预期
//	字段缺失   field_missing   单元格存在性     必填单元格为空，或该列根本不存在
//	内容损坏   content_corrupt 单元格内容       单元格有值但解释不出
//
// 于是「金额列空着」是字段缺失，「金额列写着 abc」是内容损坏——两者对用户的
// 提示完全不同（补数据 vs 查文件），合并成一类就没法给出 D-3 要求的明确提示。
// 这条划界直接决定了 currency.ErrEmptyCode 映射到字段缺失、而
// currency.ErrUnknownCode 映射到内容损坏。
//
// # i18n 契约
//
// 本包声明 7 个文案键，**语言文件必须包含它们全部**（与 rule/passwd
// KeyGenerateFailed 同例）。键与占位参数见 errors.go 各常量的注释。
// 错误里只放键与具名占位参数，不写死中文文案（K-4）。
//
// # 并发
//
// Registry 构造完成即只读，可并发读（无锁，见 registry.go）。Parser 的具体
// 实现是否可并发调用由实现自己声明；本包对 Input 只读，不持有它。
package parser

import (
	"context"

	"github.com/cellargalaxy/jotcash/internal/base/calendar"
	"github.com/cellargalaxy/jotcash/internal/base/decimal"
	"github.com/cellargalaxy/jotcash/internal/currency"
	"github.com/cellargalaxy/jotcash/internal/enum"
)

// Input 是一次解析的全部输入，即 D-2 所要求的「文件内容 + 文件密码」。
//
// 不收 entity.File：承载明写本包不依赖 entity。File 上另外 9 个字段
// （ID、归属用户、来源审计、文件名、大小、校验值、上传时间等）与解析这件事
// 无关，收进来只会让 L4 实现有机会去读它们，进而与实体耦合。
//
// 也不收文件路径或 io.Reader：终版 §四 4 定死文件内容是「原始二进制随记录
// 存储，无外部存储位置」，解析发生在内容已在内存中之后（C-1 上传即入库）。
// 收 []byte 而非 io.Reader，是因为多数账单格式（Excel、加密 PDF）本身就需要
// 随机访问，Reader 会迫使每个实现自己先读全量、反而多一层。
type Input struct {
	// Content 文件的原始二进制内容，对应 entity.File.Content。
	//
	// 本包与各实现**只读**本切片，不修改、不持有超出 Parse 调用期。
	//
	// 允许为空切片（零字节文件）：那是「格式不符」或「内容损坏」的判定素材，
	// 不是本层该拦的输入错误——具体归哪一类由实现按自己的版式决定。
	Content []byte

	// Password 文件密码，加密文档的解密口令；非加密文档为空
	// （entity.File 上的唯一非必填项，终版 §四 4）。
	//
	// 明文传递是前提 1 的直接后果（数据一律明文存储，含上传文件与文件密码，
	// 唯一例外是 User 的登录密码）。C-2 明写保存它的目的是「供重新打开」。
	//
	// **不得打印本字段**，也不得把它放进任何错误的占位参数里：解密失败时只报
	// KeyDecryptFailed（不带口令），见 NewDecryptFailedError。这不是密码红线的
	// 要求（分层 §九 的密码红线管的是用户登录密码），而是常识——把口令写进
	// 日志等于把它复制到第二个地方。
	Password string
}

// RawRow 是**原始交易行**：解析器从账单里逐行读出的、尚未成为 entity.Expense
// 的中间形态，恰含承载点名的 8 个字段。
//
// # 全部字段零值合法，「解析不出则留空」
//
// 承载明写这条。它对 8 个字段一律成立，而不只对 D-2 点名可留空的卡片三属性：
//
//   - 卡片三属性（银行名称 / 卡号后四位 / 卡片币种）：D-2 明写「解析不出则留空，
//     由用户在预览页补」。
//   - 支出日期 / 金额 / 币种：在 entity.Expense 上是必填，但**必填性不在本层
//     校验**（见包注释「不做业务必填校验」）。一个实现完全可以先把能读到的
//     填上、把读不到的留空并同时返回字段缺失错误，让错误信息带上行号。
//   - 对手方 / 备注：在 entity.Expense 上本就允许为空。
//
// 因此 RawRow 是**纯数据载体，没有方法、没有校验、没有不变式**——与
// entity 的 5 个实体同一取向（分层 §六 L1「零方法」）。
//
// # 为什么恰是这 8 个字段
//
// 承载逐字点名了这 8 项。终版 §四 3 的 Expense 有 22 项属性，其余 14 项一律
// 不进本结构，其中 4 项是**刻意排除**、必须留在各自唯一的来源处：
//
//	折算汇率     只能来自 service/fx（I-3/I-4）。放进来 = 解析器凭账单文本猜汇率，
//	             绕过 I-5「重拉失败转必填、不静默按 1:1 处理」
//	本位币金额   只能来自 rule/convert（不变式 1a 唯一实现处）。放进来直接违反
//	             前提 6「本位币金额是只读因变量，无人工指定入口」
//	摊分月数     来自用户输入、默认 1（H-1）；起止月由 rule/amortize 派生
//	             （不变式 1b）。放进来 = 起止月出现第二处派生
//	支出类型     G-3 的自动打标随 T4 挂起，**当前一律留空**。放进来 = 把挂起的
//	             T4 偷偷实现了一半
//
// 余下 10 项（ID、归属用户、来源文件、来源审计、创建/更新时间、删除标记等）
// 是入库时才产生的，与账单文本无关。
//
// # 与 entity.Expense 的映射归 service/intake
//
// 承载末句明写。本包不提供 ToExpense 之类的方法：那需要 import entity，
// 且映射时还要注入归属用户、来源文件、来源审计并跑 rule/convert 与
// rule/amortize——那是 L5 的编排，不是端口层该知道的事。
type RawRow struct {
	// Date 支出日期（终版 §四 3 必填项之一）。
	//
	// 用 calendar.Date 而非裸 string 或 time.Time（分层 §六 L1.1）：前者绕过
	// 了「恒为 10 字符、字典序 = 时间序」这条 store/sqlite 直接依赖的性质，
	// 后者带时区与时分秒——账单上的日期没有这些，转换时必然要凭空补一个时区。
	//
	// 零值即 IsZero()，表示「解析不出」。
	Date calendar.Date

	// Amount 支出金额，**原币**（终版 §四 3 必填项之一）。
	//
	// 允许为负：退款与冲正走负数（终版 §四 3），账单里的退款行直接映射过来。
	// 零值 0 与「解析不出」在本字段上**不可区分**——这是刻意接受的：Decimal
	// 的零值就是 0，要区分就得上指针或额外的布尔量，而实现真正需要区分时应当
	// 直接返回字段缺失错误，而不是靠一个「填了 0 还是没填」的哨兵值传话。
	Amount decimal.Decimal

	// Currency 支出币种，即 Amount 的币种（终版 §四 3 必填项之一）。
	//
	// 用 currency.Code：它把「已启用 / 小数位数」这些口径收在一处（T35/T38）。
	// 零值即 IsZero()，表示「解析不出」。
	//
	// 注意本字段是**支出币种**，与 CardCurrency（卡片币种）是两回事：同一张
	// USD 卡上可能刷出一笔 EUR 消费。
	Currency currency.Code

	// Counterparty 对手方（商户名、收款人等），终版 §四 3 允许为空。
	Counterparty string

	// Remark 备注，终版 §四 3 允许为空。
	//
	// 账单里常见的「摘要 / 交易说明 / 附言」一类列落在这里。具体哪一列映射到
	// 本字段由各实现决定——不同银行的列名与语义不同，端口层不做规定。
	Remark string

	// BankName 银行名称，卡片三属性之一；**解析不出则留空，由用户在预览页补**
	// （D-2）。
	BankName string

	// CardLast4 卡号后四位，卡片三属性之一；解析不出则留空（D-2）。
	//
	// 用 string 而非整数：后四位可能以 0 开头（如 "0042"），整数会丢掉前导零。
	// 本层不校验「是否恰 4 位数字」——那是版式相关的判定，归实现与预览页。
	CardLast4 string

	// CardCurrency 卡片币种，卡片三属性之一；解析不出则留空（D-2）。
	//
	// 与 Currency（支出币种）是正交两列，见 Currency 的注释。
	CardCurrency currency.Code
}

// Parser 是账单解析器接口，即 D-1 所说「新增银行 = 新增一个平级子包」的那个
// 接口。实现体一律在 L4（parser/csv、将来的 parser/pdf 等），由 app 注入
// 本包的 Registry（约定 8）。
//
// # 实现约定
//
//  1. **Type 必须恒定**：同一个实例每次调用都返回同一个键，且该键必须是
//     enum.ParserType 的合法值。NewRegistry 在构造期校验这条。
//  2. **Parse 只读 Input**：不得修改 Input.Content，不得持有它超出调用期。
//  3. **错误一律用本包的构造函数产出**（NewFormatMismatchError 等），从而带上
//     D-3 的分类与文案键。直接返回裸 error 会让上层无法分档，K-4 的前端提示
//     也取不到词。
//  4. **不做写操作、不落库、不打审计**：那些归 L5。
type Parser interface {
	// Type 返回本解析器的类型键，即 entity.File.ParserType 里存的那个值
	// （终版 §五 2：库中只存键，实现体不在枚举里）。
	//
	// 由实现自报而非在注册时另传一个 key 参数：那样「键」与「实现」是两个
	// 可以各自写错的输入，实测形态是把 CSV 实现注册到 PDF 的键下——用户上传
	// PDF、选 PDF 解析器，走进 CSV 实现后报「格式不符」，而根因在装配处，
	// 离现场极远。自报键让这种错配在结构上不可能出现。
	Type() enum.ParserType

	// Parse 把文件内容解析成原始交易行序列。
	//
	// 返回值语义：
	//   - (行序列, nil)  成功。允许返回空序列（账单确实没有交易行），
	//     此时上层按 D-4「解析出 0 条」处理，不是错误。
	//   - (nil, 非 nil)  失败，错误必为 D-3 五类之一，带文案键。
	//
	// # 快速失败，不返回半批数据
	//
	// 遇到第一个不可解析的行即返回错误，**不做「尽力解析 + 收集全部错误」**。
	// 两条理由：
	//   - D-7 是「一次提交生成一条审计」的整批语义，半批数据不可入库；
	//   - 账单是机器导出的规整文本，一行解不出通常意味着选错了解析器或文件
	//     损坏，后续行几无例外全错，报 400 条同样的错误对用户毫无增益。
	//
	// 将来若真需要多错聚合，由实现返回一个聚合错误即可（error 是接口），
	// 本接口与本包的分类函数都不必改。
	//
	// ctx 用于取消与向 base/log 透传请求标识（约定 4）；端口层不读 ctx 里的
	// 任何值，实现应在长耗时循环里检查 ctx.Err()。
	Parse(ctx context.Context, in Input) ([]RawRow, error)
}
